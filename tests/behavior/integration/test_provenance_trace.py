def test_trace_merged_clause_with_two_provenances(tmp_path: Path, capsys) -> None:
    """A clause merged from two molecules' fragments (contracts/cli-surface.md
    sample) prints every provenance record, and its bare fragment id (shared
    by both molecules) is rejected as ambiguous."""
    repo = tmp_path / "consumer"
    repo.mkdir()
    (repo / ".spaex").mkdir()
    (repo / ".spaex/constitution.md").write_text(
        _spaex_md(
            {
                "MUST": [
                    _clause(
                        "MUST run the project's test suite before creating "
                        "any commit",
                        "com.example.strict-testing/tests-before-commit",
                        "com.example.qa-baseline/tests-before-commit",
                    )
                ]
            }
        ),
        encoding="utf-8",
    )
    _write_fragment(
        repo,
        molecule_id="com.example.strict-testing",
        fragment_id="tests-before-commit",
        atom_source="hooks.test-runner",
        modality="MUST",
        body="**MUST** run the project's test suite before creating any commit.",
    )
    _write_fragment(
        repo,
        molecule_id="com.example.qa-baseline",
        fragment_id="tests-before-commit",
        atom_source="qa.tests-before-commit",
        modality="MUST",
        body="**MUST** run the project's test suite before creating any commit.",
    )
    _write_manifest(
        repo,
        compounds=[
            {
                "source": "https://github.com/haexmas/atoms",
                "revision": "a" * 40,
                "molecules": ["com.example.strict-testing"],
            },
            {
                "source": "https://github.com/haexmas/qa-atoms",
                "revision": "b" * 40,
                "molecules": ["com.example.qa-baseline"],
            },
        ],
    )

    rc = main(
        [
            "--repo-root",
            str(repo),
            "constitution",
            "trace",
            "com.example.strict-testing/tests-before-commit",
        ]
    )
    out = capsys.readouterr().out
    assert rc == 0
    assert "- com.example.strict-testing/tests-before-commit" in out
    assert "- com.example.qa-baseline/tests-before-commit" in out
    assert "Atom:    hooks.test-runner" in out
    assert "Atom:    qa.tests-before-commit" in out
    assert f"https://github.com/haexmas/atoms@{'a' * 40}" in out
    assert f"https://github.com/haexmas/qa-atoms@{'b' * 40}" in out

    # the shared bare fragment id is ambiguous across the two molecules
    rc = main(
        ["--repo-root", str(repo), "constitution", "trace", "tests-before-commit"]
    )
    out = capsys.readouterr().out
    assert rc == 1
    assert "ambiguous" in out


def test_trace_project_local_source(tmp_path: Path, capsys) -> None:
    """A project-local fragment's provenance has no pinned molecule; the
    Molecule line names it as project-local instead of a source@revision."""
    repo = tmp_path / "consumer"
    repo.mkdir()
    (repo / ".spaex").mkdir()
    (repo / ".spaex/constitution.md").write_text(
        _spaex_md(
            {
                "SHOULD": [
                    _clause(
                        "SHOULD prefer small commits",
                        "_project/small-commits",
                    )
                ]
            }
        ),
        encoding="utf-8",
    )
    _write_fragment(
        repo,
        molecule_id="_project",
        fragment_id="small-commits",
        atom_source="_project",
        modality="SHOULD",
        body="**SHOULD** prefer small commits.",
    )
    (repo / ".spaex/manifest.json").write_text(
        json.dumps(
            {
                "spaex_version": "4",
                "identity": "com.example.trace-consumer",
                "compounds": [],
            }
        ),
        encoding="utf-8",
    )

    rc = main(
        ["--repo-root", str(repo), "constitution", "trace", "_project/small-commits"]
    )
    out = capsys.readouterr().out
    assert rc == 0
    assert "project-local" in out
