"""Render, parse and verify the composed constitution, format version 2 (Spec 030).

spaex itself writes the text: every fragment body in scoped-id order, CRLF and
CR canonicalized to LF and nothing else changed, with the passages the operator
did not keep commented out. No language model is involved and the output is a
pure function of the fragments and the valid decisions. Layout:
contracts/spaex-md-format-v2.md.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass

from spaex.behavior.decisions import FORMAT_VERSION, Decision
from spaex.behavior.fragment import BehaviorFragment
from spaex.behavior.passages import canonical_body, canonical_lines, locate

TITLE = "# spaex Behavior Harness"
NOTICES = (
    "_This file is generated by `spaex install`. Do not edit by hand._",
    "_Change fragments in `.spaex/constitution.d/` and re-run install. "
    "Text inside a comment marked `spaex-excluded` is not an instruction._",
)
_END_BLOCK = "<!-- /spaex-fragment -->"
_END_EXCLUSION = "-->"
_ESCAPED_END = "--&gt;"

_HEADER_RE = re.compile(
    r'^<!--\s*spaex-composed:'
    r'source_hash="(?P<source_hash>[0-9a-f]{64})"\s+'
    r'build_input_hash="(?P<build_input_hash>[0-9a-f]{64})"\s+'
    r'version="(?P<version>\d+)"\s*-->$'
)
_BLOCK_START_RE = re.compile(
    r'^<!-- spaex-fragment id="(?P<id>[^"]+)"(?: modality="(?P<modality>[A-Z_]+)")? -->$'
)
_EXCLUSION_START_RE = re.compile(
    r'^<!-- spaex-excluded kept="(?P<kept>[^"]*)" decision="(?P<decision>[^"]*)"$'
)


class RenderError(ValueError):
    """Raised when a composed document is malformed or does not match its source."""


@dataclass(frozen=True)
class ExcludedRange:
    """Lines `start`..`end` of one fragment body that the operator did not keep."""

    scoped_id: str
    start: int
    end: int
    kept: tuple[str, ...]
    decisions: tuple[str, ...]


def excluded_ranges(
    fragments: Sequence[BehaviorFragment], decisions: Sequence[Decision]
) -> dict[str, list[ExcludedRange]]:
    """Ranges to comment out per fragment, overlapping ranges merged, in line order."""
    index = {fragment.scoped_id: fragment for fragment in fragments}
    per_fragment: dict[str, list[ExcludedRange]] = {}
    for decision in sorted(decisions, key=lambda d: d.key):
        if decision.choice.kind != "keep":
            continue
        located: list[tuple[str, int, int]] = []
        for ref in decision.passages:
            fragment = index.get(ref.scoped_id)
            span = locate(fragment, ref.text) if fragment is not None else None
            if span is None:
                raise RenderError(
                    f"decision {decision.key[:12]}: passage of {ref.scoped_id} is not unique"
                )
            located.append((ref.scoped_id, span[0], span[1]))
        kept_id, kept_start, kept_end = located[decision.choice.kept or 0]
        kept_ref = f"{kept_id}:{kept_start}-{kept_end}"
        for position, (scoped_id, start, end) in enumerate(located):
            if position == decision.choice.kept:
                continue
            per_fragment.setdefault(scoped_id, []).append(
                ExcludedRange(
                    scoped_id=scoped_id,
                    start=start,
                    end=end,
                    kept=(kept_ref,),
                    decisions=(decision.key[:12],),
                )
            )
    return {scoped_id: _merge(ranges) for scoped_id, ranges in per_fragment.items()}


def _merge(ranges: list[ExcludedRange]) -> list[ExcludedRange]:
    merged: list[ExcludedRange] = []
    for current in sorted(ranges, key=lambda r: (r.start, r.end)):
        if merged and current.start <= merged[-1].end:
            last = merged[-1]
            merged[-1] = ExcludedRange(
                scoped_id=last.scoped_id,
                start=last.start,
                end=max(last.end, current.end),
                kept=tuple(sorted(set(last.kept) | set(current.kept))),
                decisions=tuple(sorted(set(last.decisions) | set(current.decisions))),
            )
        else:
            merged.append(current)
    return merged


def render(
    fragments: Sequence[BehaviorFragment],
    decisions: Sequence[Decision],
    *,
    source_hash: str,
    build_input_hash: str,
    preamble: str = "",
) -> str:
    """The composed constitution, version 2, for these fragments and decisions."""
    excluded = excluded_ranges(fragments, decisions)
    out: list[str] = [
        f'<!-- spaex-composed:source_hash="{source_hash}" '
        f'build_input_hash="{build_input_hash}" version="{FORMAT_VERSION}" -->'
    ]
    out.extend([TITLE, "", *NOTICES])
    if preamble:
        out.extend(["", preamble.removesuffix("\n")])
    for fragment in sorted(fragments, key=lambda f: f.scoped_id):
        out.append("")
        marker = f'<!-- spaex-fragment id="{fragment.scoped_id}"'
        if fragment.modality is not None:
            marker += f' modality="{fragment.modality.value}"'
        out.append(marker + " -->")
        out.extend(_body_lines(fragment, excluded.get(fragment.scoped_id, [])))
        out.append(_END_BLOCK)
    return "\n".join(out) + "\n"


def _body_lines(fragment: BehaviorFragment, ranges: list[ExcludedRange]) -> list[str]:
    lines = canonical_lines(fragment.body)
    result: list[str] = []
    position = 0
    for excluded in ranges:
        result.extend(lines[position : excluded.start - 1])
        result.append(
            f'<!-- spaex-excluded kept="{", ".join(excluded.kept)}" '
            f'decision="{",".join(excluded.decisions)}"'
        )
        result.extend(
            line.replace("&", "&amp;").replace(_END_EXCLUSION, _ESCAPED_END)
            for line in lines[excluded.start - 1 : excluded.end]
        )
        result.append(_END_EXCLUSION)
        position = excluded.end
    result.extend(lines[position:])
    return result


@dataclass(frozen=True)
class ParsedExclusion:
    """An exclusion comment in the composed file."""

    file_start: int
    file_end: int
    kept: tuple[str, ...]
    decisions: tuple[str, ...]
    text_lines: tuple[str, ...]


@dataclass(frozen=True)
class ParsedBlock:
    """One fragment block of the composed file (line numbers are 1-based file lines)."""

    scoped_id: str
    modality: str | None
    start_line: int
    end_line: int
    body: str
    exclusions: tuple[ParsedExclusion, ...]


@dataclass(frozen=True)
class ParsedDocument:
    source_hash: str
    build_input_hash: str
    version: str
    blocks: tuple[ParsedBlock, ...]


def parse(text: str) -> ParsedDocument:
    """Parse a version 2 composed constitution; raise `RenderError` if malformed."""
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    header = _HEADER_RE.match(lines[0]) if lines else None
    if header is None:
        raise RenderError("missing or malformed spaex-composed header line")
    blocks: list[ParsedBlock] = []
    number = 1
    while number < len(lines):
        start_match = _BLOCK_START_RE.match(lines[number])
        if start_match is None:
            number += 1
            continue
        body_lines: list[str] = []
        exclusions: list[ParsedExclusion] = []
        cursor = number + 1
        while True:
            if cursor >= len(lines):
                raise RenderError(f"fragment {start_match['id']}: block is not closed")
            line = lines[cursor]
            if line == _END_BLOCK:
                break
            exclusion_start = _EXCLUSION_START_RE.match(line)
            if exclusion_start is None:
                body_lines.append(line)
                cursor += 1
                continue
            inner: list[str] = []
            opening = cursor
            cursor += 1
            while cursor < len(lines) and lines[cursor] != _END_EXCLUSION:
                inner.append(lines[cursor])
                cursor += 1
            if cursor >= len(lines):
                raise RenderError(
                    f"fragment {start_match['id']}: exclusion comment is not closed"
                )
            unescaped = [
                row.replace(_ESCAPED_END, _END_EXCLUSION).replace("&amp;", "&")
                for row in inner
            ]
            body_lines.extend(unescaped)
            exclusions.append(
                ParsedExclusion(
                    file_start=opening + 1,
                    file_end=cursor + 1,
                    kept=tuple(p.strip() for p in exclusion_start["kept"].split(",") if p.strip()),
                    decisions=tuple(
                        p for p in exclusion_start["decision"].split(",") if p
                    ),
                    text_lines=tuple(unescaped),
                )
            )
            cursor += 1
        blocks.append(
            ParsedBlock(
                scoped_id=start_match["id"],
                modality=start_match["modality"],
                start_line=number + 2,
                end_line=cursor,
                body="\n".join(body_lines) + "\n" if body_lines else "",
                exclusions=tuple(exclusions),
            )
        )
        number = cursor + 1
    return ParsedDocument(
        source_hash=header["source_hash"],
        build_input_hash=header["build_input_hash"],
        version=header["version"],
        blocks=tuple(blocks),
    )


def verify(
    fragments: Sequence[BehaviorFragment],
    decisions: Sequence[Decision],
    text: str,
) -> None:
    """Prove that `text` carries every fragment body verbatim (FR-014, research R2).

    Reconstructs each body from the parsed document, undoing the exclusion
    comments, and compares it with the source body (LF-canonicalized). Also
    checks that the exclusions are exactly those the decisions call for.
    Raises `RenderError` naming the first difference.
    """
    document = parse(text)
    if document.version != FORMAT_VERSION:
        raise RenderError(f"format version {document.version!r} is not {FORMAT_VERSION!r}")
    expected_ids = sorted(f.scoped_id for f in fragments)
    found_ids = [block.scoped_id for block in document.blocks]
    if found_ids != expected_ids:
        missing = sorted(set(expected_ids) - set(found_ids))
        extra = sorted(set(found_ids) - set(expected_ids))
        raise RenderError(
            f"fragment blocks differ from the fragments (missing {missing}, extra {extra}, "
            "or out of order)"
        )
    excluded = excluded_ranges(fragments, decisions)
    by_id = {fragment.scoped_id: fragment for fragment in fragments}
    for block in document.blocks:
        fragment = by_id[block.scoped_id]
        if block.body != canonical_body(fragment.body):
            raise RenderError(f"{block.scoped_id}: body differs from the fragment")
        expected = excluded.get(block.scoped_id, [])
        lines = canonical_lines(fragment.body)
        expected_texts = ["\n".join(lines[r.start - 1 : r.end]) for r in expected]
        found_texts = ["\n".join(e.text_lines) for e in block.exclusions]
        if found_texts != expected_texts:
            raise RenderError(f"{block.scoped_id}: exclusions differ from the decisions")


